"""
report.py
---------
Summarises evaluation results and writes REPORT.md.

    summarize(records)                    accuracy, grounding rate, latency and Gemini calls
    write_report(runs, path, all_results) REPORT.md for one or more runs, with a table comparing all runs

The report says next to every score whether its split is held out or was tuned on (SPLIT_ROLES).
"""

import json
import textwrap
from datetime import datetime
from pathlib import Path

import numpy as np

from chatbot.eval import CATEGORIES, SPLIT_ROLES, SPLITS
from chatbot.eval.scoring import CHECKS


def summarize(records: list[dict]) -> dict:
    answered = [r for r in records if r["status"] == "ok"]
    timed = [r["elapsed_s"] for r in records if r["llm_calls"]]  # answers that reached Gemini
    return {
        "cases": len(records),
        "passed": sum(r["passed"] for r in records),
        "answered": len(answered),
        "grounded": sum(bool(r["grounding"]["verified"]) for r in answered),
        "median_s": float(np.median(timed)) if timed else None,
        "p90_s": float(np.percentile(timed, 90)) if timed else None,
        "avg_calls": float(np.mean([r["llm_calls"] for r in records])) if records else None,
    }


def write_report(runs: list[dict], path: Path, all_results: list[dict]) -> str:
    """Writes the report for one or more runs of different cases (results files as saved by the
    runner) and returns its text."""
    text = render(runs, all_results)
    path.write_text(text, encoding="utf-8")
    return text


def load_all_results(directory: Path) -> list[dict]:
    """Every results file in directory, oldest run first."""
    results = [json.loads(path.read_text(encoding="utf-8")) for path in directory.glob("*.json")]
    return sorted(results, key=lambda r: r["run"]["started"])


def render(runs: list[dict], all_results: list[dict]) -> str:
    records = [record for results in runs for record in results["records"].values()]
    splits = {split: [r for r in records if r["split"] == split] for split in SPLITS}
    present = [split for split in SPLITS if splits[split]]
    lines = ["# Evaluation report", ""]
    for results in runs:
        run, recs = results["run"], list(results["records"].values())
        counts = ", ".join(f"{n} {split}" for split in SPLITS if (n := sum(r["split"] == split for r in recs)))
        lines.append(f"- Run **{run['tag']}**, {run['updated'][:16].replace('T', ' ')}: {len(recs)} cases ({counts}), "
                     f"temperature {run['temperature']:g}, chat models {' → '.join(run['models'])}; "
                     f"API requests: {_requests(run)}.")
    lines += [
        "",
        "Generated by `python -m chatbot.eval`; the checks are defined in `chatbot/eval/scoring.py`. "
        "A case passes when every check that applies to it passes. Question embeddings are cached by the "
        "runner, so latency covers the chat calls and the SQL only.",
        "",
        _roles(present),
        "",
        "## Summary",
        "",
        "| Split | Role | Run | Passed | Accuracy | Grounded answers | Median latency | p90 latency | Avg Gemini calls |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    roles = {SPLIT_ROLES[split][0] for split in present}
    rows = [(split, SPLIT_ROLES[split][0], splits[split]) for split in present]
    for name, role, group in [*rows, ("all", roles.pop() if len(roles) == 1 else "mixed", records)]:
        if group:
            s = summarize(group)
            tags = ", ".join(r["run"]["tag"] for r in runs
                             if any(name in ("all", rec["split"]) for rec in r["records"].values()))
            lines.append(f"| {name} | {role} | {tags} | {s['passed']}/{s['cases']} | {_pct(s['passed'], s['cases'])} "
                         f"| {s['grounded']}/{s['answered']} | {_seconds(s['median_s'])} | {_seconds(s['p90_s'])} "
                         f"| {s['avg_calls']:.1f} |")

    header = f"| {' | '.join(present)} | all |"
    rule = "| --- " * (len(present) + 2) + "|"
    lines += ["", "## By category", "", f"| Category {header}", rule]
    for category in CATEGORIES:
        group = [r for r in records if r["category"] == category]
        if group:
            cells = [_fraction([r for r in group if r["split"] == split]) for split in present]
            lines.append(f"| {category} | {' | '.join(cells)} | {_fraction(group)} |")

    lines += ["", "## Checks", "", f"| Check {header}", rule]
    for check in CHECKS:
        cells = [_check_fraction(splits[split], check) for split in present] + [_check_fraction(records, check)]
        if any(cells):
            lines.append(f"| {check} | {' | '.join(cell or '–' for cell in cells)} |")

    failures = [r for r in records if not r["passed"]]
    lines += ["", f"## Failures ({len(failures)})", ""]
    for record in failures:
        lines += _failure(record)
    if not failures:
        lines.append("None.")

    lines += ["", "## All runs", "", f"| Run | Temperature | Cases | Accuracy | {' | '.join(SPLITS)} | Grounded | "
              "Median | p90 | Avg calls | Chat requests |", "| --- " * (len(SPLITS) + 9) + "|"]
    for other in all_results:
        recs, info = list(other["records"].values()), other["run"]
        s = summarize(recs)
        cells = " | ".join(_fraction([r for r in recs if r["split"] == split]) for split in SPLITS)
        lines.append(f"| {info['tag']} | {info['temperature']:g} | {s['cases']} | {_pct(s['passed'], s['cases'])} "
                     f"| {cells} | {s['grounded']}/{s['answered']} "
                     f"| {_seconds(s['median_s'])} | {_seconds(s['p90_s'])} | {s['avg_calls']:.1f} "
                     f"| {sum(n for m, n in info['api_requests'].items() if 'embedding' not in m)} |")
    return "\n".join(lines) + "\n"


def _roles(present: list[str]) -> str:
    """Which of the reported scores are held out and which were tuned on, one paragraph each."""
    paragraphs = []
    for role, label in (("held out", "Held out (questions the agent was not tuned on)"),
                        ("tuned on", "Tuned on (scores are optimistic)")):
        splits = [split for split in present if SPLIT_ROLES[split][0] == role]
        if splits:
            paragraphs.append(f"**{label}:** " + "; ".join(f"{split}, {SPLIT_ROLES[split][1]}" for split in splits) + ".")
    return "\n\n".join(paragraphs)


def _failure(record: dict) -> list[str]:
    failed = [check for check, passed in record["checks"].items() if not passed]
    grounding = record["grounding"]
    lines = [f"### {record['id']} ({record['split']}, {record['category']}): {', '.join(failed)}", "",
             f"**Q:** {record['question']}", ""]
    lines += ["> " + line if line else ">" for line in record["text"].splitlines()]
    lines.append("")
    if not grounding["verified"]:
        lines.append(f"Unverified numbers: {', '.join(grounding['unverified_numbers'])}. ")
    lines.append(f"Model {record['model']}, {record['llm_calls']} Gemini calls, {record['elapsed_s']:.1f} s, "
                 f"notes: {', '.join(record['sources']) or 'none'}.")
    for number, run in enumerate(record["sql_runs"], 1):
        outcome = f"error: {run['error']}" if run["error"] else f"{run['row_count']} rows, first: {run['preview'][:3]}"
        lines += ["", f"SQL {number} ({outcome}):", "", "```sql", textwrap.dedent(run["sql"]).strip(), "```"]
    if not record["sql_runs"]:
        lines.append("No SQL.")
    return lines + [""]


def _requests(run: dict) -> str:
    requests = run.get("api_requests") or {}
    return ", ".join(f"{model} {count}" for model, count in sorted(requests.items())) or "none"


def _fraction(records: list[dict]) -> str:
    return f"{sum(r['passed'] for r in records)}/{len(records)}" if records else "–"


def _check_fraction(records: list[dict], check: str) -> str:
    applicable = [r["checks"][check] for r in records if check in r["checks"]]
    return f"{sum(applicable)}/{len(applicable)}" if applicable else ""


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%" if whole else "–"


def _seconds(value: float | None) -> str:
    return "–" if value is None else f"{value:.1f} s"


def now() -> str:
    return datetime.now().isoformat(timespec="seconds")
